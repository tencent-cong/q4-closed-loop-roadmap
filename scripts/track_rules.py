import re
# 赛道口径补充规则（2026-10-12 用户确认）：清洁工具赛道只含物理清洁工具（拖把、抹布、刷子、垃圾袋、吸油纸等），
# 化学清洁（清洁剂/除味剂/杀虫驱虫/洗衣类/除湿干燥剂等）不属于我们的赛道，统计时整体剔除。
CHEM_RE = re.compile(
    r"清洁剂|清洗剂|洗洁精|洁厕|泡腾|疏通剂|除味|除臭|芳香|空气净化|香薰|甲醛|除菌|除螨喷雾|消毒|除霉|"
    r"驱虫|驱鼠|灭鼠|粘鼠|捕鼠|灭蚊|灭蝇|灭蚁|蚊香|蟑螂|灭蟑|杀虫|防霉|防蛀|驱蚊|"
    r"洗衣|干洗|去渍|漂白|彩漂|柔顺|留香|吸色|爆炸盐|衣领净|洗衣皂|内衣皂|衣物消毒|"
    r"保养剂|护理剂|护理$|干燥剂|除湿|祛螨|除螨贴|"
    r"玻璃水|车蜡|镀膜|清新剂|除锈|防雾|润滑|冷媒|补漆|翻新剂|洗车液|汽车清洁"
)

def is_chem(category_path: str) -> bool:
    """只对清洁工具赛道调用：剥掉二级固定前缀后，类目路径命中化学清洁关键词即剔除。"""
    p = str(category_path).replace("洗护清洁/除臭剂/纸品-", "").replace("家庭清洁纸品-", "").replace("室内除臭/除味用品-", "")
    return bool(CHEM_RE.search(p))

