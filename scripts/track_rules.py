# 2026-10-12 用户补充口径：
# 1) 泡脚桶/足浴桶、沐浴桶/泡澡桶、搓澡工具 属于清洁工具（洗浴工具），不归功效品。
# 2) 手霜、足霜等手足护理属于个护，不在赛道内，整体删除。
TRACK_OVERRIDE_RE = [
    (re.compile(r"足浴桶|足浴器|足浴盆|泡脚桶|泡澡桶|沐浴桶|浴桶|搓澡"), "清洁工具"),
    # 3) 密封罐/保鲜盒/保鲜袋/保鲜膜/米桶 等食品储存归收纳用品（2026-10-12）
    (re.compile(r"密封罐|储物罐|保鲜盒|保鲜袋|保鲜膜|米桶|米箱"), "收纳用品"),
]
DROP_CAT_RE = re.compile(r"足霜|护手霜|手部护理|手部洗护|其他足部洗护|足膜")

def apply_overrides(track, category_path):
    """返回调整后的赛道；None 表示剔除。"""
    p = str(category_path)
    if DROP_CAT_RE.search(p):
        return None
    for rx, t in TRACK_OVERRIDE_RE:
        if rx.search(p):
            return t
    return track

